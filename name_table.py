def translate(name):
    """One kana reading -> hanzi, longest match first, per mora as fallback."""
    if name in GIVEN:
        return GIVEN[name]
    if name in SURNAME:
        return SURNAME[name]
    out = []
    i = 0
    while i < len(name):
        for ln in (4, 3, 2, 1):
            part = name[i:i + ln]
            if part in MORPH:
                out.append(MORPH[part])
                i += ln
                break
        else:
            out.append('')
            i += 1
    return ''.join(out)


