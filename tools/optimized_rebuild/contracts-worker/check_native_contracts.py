def verify(rom, strict_source=True):
    V = []          # violations: {'tag', 'message'}
    C = {}          # contracts

    def bad(tag, msg):
        V.append({'tag': tag, 'message': msg})

    # ---- 1. source identity -------------------------------------------
    C['source'] = {
        'size': len(rom),
        'crc32': '%08X' % (zlib.crc32(rom) & 0xFFFFFFFF),
        'sha256': hashlib.sha256(rom).hexdigest(),
    }
    if strict_source:
        if len(rom) != EXPECT['source']['size']:
            bad('source.size', 'size %d != %d' % (len(rom), EXPECT['source']['size']))
        if C['source']['crc32'] != EXPECT['source']['crc32']:
            bad('source.crc32', 'crc32 %s != %s' % (C['source']['crc32'],
                                                    EXPECT['source']['crc32']))
        if C['source']['sha256'] != EXPECT['source']['sha256']:
            bad('source.sha256', 'sha256 %s != %s' % (C['source']['sha256'],
                                                      EXPECT['source']['sha256']))

    # ---- 6a. raw byte locks -------------------------------------------
    C['byte_locks'] = {}
    for key, hexs in sorted(EXPECT['hexlocks'].items()):
        # key format: name_BBAAAA_len
        parts = key.rsplit('_', 2)
        cpu_s = parts[-2]
        bank = int(cpu_s[:2], 16)
        addr = int(cpu_s[2:], 16)
        off = c2f(bank, addr)
        want = bytes.fromhex(hexs)
        got = rom[off:off + len(want)]
        ok = got == want
        C['byte_locks'][key] = {'bank': '%02X' % bank, 'addr': '%04X' % addr,
                                'len': len(want), 'matched': ok}
        if not ok:
            bad('lock', '%s at %02X:%04X differs (got %s)' %
                (key, bank, addr, got.hex()))

    # ---- 6b. name records / parameter region ---------------------------
    C['names'] = {}
    hdr_start = u16(rom, 0x48000)
    hdr_end = u16(rom, 0x48002)
    C['names']['header'] = {'start': hdr_start, 'end': hdr_end}
    if (hdr_start, hdr_end) != (EXPECT['name']['start'], EXPECT['name']['end']):
        bad('names.header', 'header %04X/%04X != %04X/%04X' %
            (hdr_start, hdr_end, EXPECT['name']['start'], EXPECT['name']['end']))
    span = hdr_end - hdr_start
    if span != EXPECT['name']['count'] * 16 or span <= 0:
        bad('names.count', 'span %d != %d records * 16' %
            (span, EXPECT['name']['count']))
    n = max(0, span // 16)
    C['names']['records'] = n
    C['names']['sample'] = {}
    for i in range(min(n, 600)):
        o = 0x48000 + (hdr_start - 0x8000) + i * 16
        name, ok = decode_name(rom, rom[o:o + 4])
        if not ok or not name:
            bad('names.decode', 'record %d at $09:%04X not kana-only: %r (bytes %s)' %
                (i, hdr_start + i * 16, name, rom[o:o + 4].hex()))
        if i in EXPECT['name']['anchors']:
            C['names']['sample'][i] = name
            if name != EXPECT['name']['anchors'][i]:
                bad('names.anchors', 'record %d = %r, expected %r' %
                    (i, name, EXPECT['name']['anchors'][i]))
    # the 19-entry parameter pointer table right after the header word
    ptrs = [u16(rom, 0x48004 + 2 * i) for i in range(19)]
    C['names']['param_ptrs'] = ['%04X' % p for p in ptrs]
    if ptrs != EXPECT['param_ptrs']:
        bad('names.params', 'pointer table %s != %s' %
            (['%04X' % p for p in ptrs], ['%04X' % p for p in EXPECT['param_ptrs']]))
    if not all(ptrs[i] < ptrs[i + 1] for i in range(18)):
        bad('names.params_order', 'parameter pointers not strictly increasing')
    if ptrs and ptrs[0] <= hdr_end:
        bad('names.params_bound', 'first parameter pointer %04X not past table end %04X'
            % (ptrs[0], hdr_end))
    C['names']['param_region'] = 'starts at $09:%04X (non-text: 19 pointer blocks + record parameter bytes 4..15)' % hdr_end

    # ---- 3./4. text loader + stream + extension table -------------------
    C['text_loader'] = {}
    C['text_loader']['sites'] = {
        'pointer_setup_patched_at': '$03:EB70 (JML $22:8000)',
        'byte_fetch_patched_at': '$03:EBBB (JML $22:8050)',
    }
    # semantic sequence checks inside the (locked) bank22 code
    code = rom[c2f(0x22, 0x8000):c2f(0x22, 0x8000) + 0x6D]

    def has_seq(seq, what):
        k = code.find(bytes.fromhex(seq))
        C['text_loader'][what] = (k >= 0)
        if k < 0:
            bad('loader.seq', 'bank22 code lacks %s (%s)' % (what, seq))

    has_seq('AD4B03C903B008', 'LDA $034B / CMP #$03 / BCS')
    has_seq('AD4A030A5C74EB03', 'LDA $034A / ASL / JML $03EB74 (original path)')
    has_seq('38E9038D4B03', 'SEC / SBC #$03 / STA $034B (index - $300)')
    has_seq('186970', 'ADD #$70 (table base low, $8070)')
    has_seq('6980', 'ADD #$80 (high byte, bank $22 window)')
    has_seq('A92248AB', 'DBR=$22 before table read')
    has_seq('B12048C8B1208D6B0368', 'read u16 LE, store $036B then $036A')
    has_seq('5C9AEB03', 'JML $03EB9A (CLC / RTS return)')
    has_seq('B12085125CBFEB03', 'stream: fetch byte, STA $12, JML $03:EBBF')
    has_seq('A92348AB', 'stream: DBR=$23 (extended text bank)')
    C['text_loader']['contract'] = {
        'index': 'i = $034A + 256*$034B (16-bit)', 'extension_when': '$034B >= 3 (i >= $300)',
        'record_of': 'for $034B < 3 the original path continues at $03:EB74 (A = $034A<<1)',
        'table': '$22:8070 + 2*(i - $300), 16-bit little-endian',
        'pointer_meaning': 'address inside bank $23 (>= $8000)',
        'return': 'CLC+RTS via $03:EB9A (index 0 -> SEC+RTS via $03:EB9C)',
        'stream': 'byte = [bank:$23|caller][$20/$21], Y; A and $12 = byte; JML $03:EBBF',
        'width': 'text code = 1 byte (A/$12); index = 16-bit split as $034A/$034B; '
                 'table entry = 16-bit LE; stream pointer = 16-bit',
        'dbr': '$22 while reading the pointer table; $23 for extended stream bytes; '
               'PHB/PLB around both, restored before every JML back',
        'dp': "scratch $20/$21 and result $12 live on the caller's direct page (D is "
              "never reloaded here), exactly like the original loader path",
    }
    # extension table
    tbl = [u16(rom, 0x110070 + 2 * i) for i in range(76)]
    C['text_extension'] = {'table_base': '$22:8070', 'entries': 76,
                           'first': '%04X' % tbl[0], 'last': '%04X' % tbl[-1]}
    if tbl != EXPECT['ext_table']:
        bad('ext.table', 'extension table differs from the pinned 76 entries')
    if tbl[0] != 0:
        bad('ext.sentinel', 'entry[0] (message $300) = %04X, expected $0000' % tbl[0])
    if tbl[1] != 0x8000:
        bad('ext.first', 'entry[1] (message $301) = %04X, expected $8000' % tbl[1])
    if not all(tbl[i] < tbl[i + 1] for i in range(1, 75)):
        bad('ext.monotonic', 'extension pointers not strictly increasing')
    if not all(0x8000 <= p < 0x8740 for p in tbl[1:]):
        bad('ext.range', 'extension pointer outside bank-$23 text span')
    for i, p in enumerate(tbl[1:], 1):
        b = rom[0x118000 + (p - 0x8000)]
        if b not in (0xE2, 0xF0, 0xF3):
            bad('ext.start', 'message %03X starts with %02X (not E2/F0/F3)' % (0x300 + i, b))
    # bank $23 span
    span23 = [i for i, c in enumerate(rom[0x118000:0x120000]) if c]
    C['text_extension']['bank23_span'] = ['$%04X' % (0x8000 + span23[0]),
                                          '$%04X' % (0x8000 + span23[-1] + 1)]
    if (span23[0], span23[-1]) != (0, 0x73F):
        bad('bank23.span', 'bank23 text span %04X-%04X != 8000-873F' %
            (span23[0], span23[-1]))
    if any(rom[0x118740:0x118800]):
        bad('bank23.tail', 'nonzero bytes after the text end at $23:8740')
    # optional cross-check against the inventory extraction
    nt = ROOT / 'optimization-new-text.json'
    if nt.exists():
        msgs = sorted(json.load(open(nt, encoding='utf-8')), key=lambda r: r['id'])
        okj = len(msgs) == 75 and [m['id'] for m in msgs] == list(range(0x301, 0x34C))
        if okj:
            for i, m in enumerate(msgs):
                want = 0x8000 + (m['offset'] - 0x118000)
                if want != tbl[i + 1]:
                    okj = False
                    break
        C['text_extension']['new_text_json_crosscheck'] = okj
        if not okj:
            bad('ext.json', 'table disagrees with optimization-new-text.json')
    else:
        C['text_extension']['new_text_json_crosscheck'] = None

    # ---- 5. six-command pause menu -------------------------------------
    C['menu'] = {
        'entry': '$00:F580 -> JML $20:9020 (Six-way dispatcher; $0368 = item+$80 sign)',
        'items': 6,
        'new_item_index_4': '$20:9058, the added どうしうち command',
        'label_blob': '$03:F743 (52 cells, copied to $040A by $20:9090)',
        'label_drawer': '$03:F95D (per-cell FB upper / FA lower via the 2-byte records)',
        'cursor_drawer': '$03:F8BD reads $039F (row) + $0391 and $03A0 (col)',
        'index': '$039A = cursor item; $039F/$03A0 = (row, col) from the tables below',
    }
    rows = list(rom[0x1F845:0x1F845 + 6])
    cols = list(rom[0x1F84B:0x1F84B + 6])
    C['menu']['table_rows_F845'] = ['%02X' % b for b in rows]
    C['menu']['table_cols_F84B'] = ['%02X' % b for b in cols]
    C['menu']['coordinates'] = [{'item': i, 'row': rows[i], 'col': cols[i]}
                                for i in range(6)]
    if rows != [0, 0, 0, 1, 1, 1] or cols != [0, 10, 20, 0, 10, 20]:
        bad('menu.tables', 'coordinate tables %s/%s changed' % (rows, cols))
    blob = rom[0x1F743:0x1F743 + 0x34]
    C['menu']['blob_sha1'] = hashlib.sha1(blob).hexdigest()
    if C['menu']['blob_sha1'] != EXPECT['blob_f743_sha1']:
        bad('menu.blob', 'label blob sha1 %s != %s' %
            (C['menu']['blob_sha1'], EXPECT['blob_f743_sha1']))
    C['menu']['labels_decoded'] = EXPECT['menu_labels']

    # ---- 6c. inbound entry sites ---------------------------------------
    C['entry_sites'] = []
    for key, e in sorted(EXPECT['entries'].items()):
        bank = int(key[:2], 16)
        cpu = int(key[3:], 16)
        off = c2f(bank, cpu)
        got_op = rom[off]
        want_op = int(e['op'], 16)
        ok = got_op == want_op
        msg = None
        if ok:
            if want_op in (0x22, 0x5C):
                tb, tc = int(e['target'][:2], 16), int(e['target'][3:], 16)
                if (rom[off + 1] | rom[off + 2] << 8, rom[off + 3]) != (tc, tb):
                    ok, msg = False, 'target bytes differ'
            ab = align_back(rom, bank, cpu)
            if ok and ab != e['align']:
                ok, msg = False, 'boundary evidence changed (align_back %s != %s)' % (
                    ab, e['align'])
            if ok:
                refs = sweep_refs(rom, tb, tc) if want_op in (0x22, 0x5C) else []
                if refs != e['refs']:
                    ok, msg = False, 'stub sweep refs %s != %s' % (refs, e['refs'])
        if not ok:
            bad('entry.sites', '%s %02X:%04X changed (%s)' % (
                {0x22: 'JSL', 0x5C: 'JML'}.get(want_op, '?'), bank, cpu,
                msg or 'opcode'))
        C['entry_sites'].append({'site': '%02X:%04X' % (bank, cpu), 'op':
                                 {0x22: 'JSL', 0x5C: 'JML'}.get(want_op, '?'),
                                 'target': e['target'], 'align_back': e['align'],
                                 'return_refs': e['refs'], 'verified': ok})
    if len([s for s in C['entry_sites'] if s['verified']]) != len(EXPECT['entries']):
        bad('entry.count', 'expected %d verified direct entries' % len(EXPECT['entries']))
    # rejected byte patterns (JML[ind] opcodes that live in data blocks)
    C['rejected_patterns'] = []
    for key, r in sorted(EXPECT['rejected'].items()):
        bank = int(key[:2], 16)
        cpu = int(key[3:], 16)
        off = c2f(bank, cpu)
        w = hashlib.sha1(rom[off - 0x10:off + 0x20]).hexdigest()
        ok = rom[off] == 0xDC and w == r['window_sha1']
        if not ok:
            bad('rejected.patterns', '%s no longer the pinned data pattern' % key)
        C['rejected_patterns'].append({
            'site': key, 'byte': 'DC', 'reason': r['reason'],
            'window_sha1': r['window_sha1'], 'matched': ok})
    if len(C['rejected_patterns']) != 5:
        bad('rejected.count', 'expected 5 rejected data patterns')

    # ---- 7. bank block maps ---------------------------------------------
    C['bank_blocks'] = {}
    for bank in (0x20, 0x22, 0x23):
        off = bank * 0x8000
        chunk = rom[off:off + 0x8000]
        whole = hashlib.sha1(chunk).hexdigest()
        C['bank_blocks']['%02X' % bank] = {
            'sha1': whole,
            'expected_sha1': EXPECT['bank_sha1']['%02X' % bank]}
        if whole != EXPECT['bank_sha1']['%02X' % bank]:
            bad('bank.sha', 'bank %02X sha1 differs' % bank)
        runs = []
        inrun = False
        for i, c in enumerate(chunk):
            if c and not inrun:
                start = i
                inrun = True
            elif not c and inrun:
                runs.append((start, i))
                inrun = False
        if inrun:
            runs.append((start, len(chunk)))
        merged = []
        for s, e in runs:
            if merged and s - merged[-1][1] <= 8:
                merged[-1] = (merged[-1][0], e)
            else:
                merged.append((s, e))
        got = [{'start': 0x8000 + s, 'end': 0x8000 + e,
                'sha1': hashlib.sha1(chunk[s:e]).hexdigest()} for s, e in merged]
        want = EXPECT['blocks']['%02X' % bank]
        if got != want:
            bad('bank.blocks', 'bank %02X block map differs' % bank)
        C['bank_blocks']['%02X' % bank]['blocks'] = got

    # ---- unconfirmed ----------------------------------------------------
    C['unconfirmed'] = EXPECT['unconfirmed']
    C['verified'] = not V
    return V, C


