def main():
    inputs = json.load(open(ROOT / 'inputs.json', encoding='utf-8'))
    path = inputs['opt']['path']
    rom = open(path, 'rb').read()
    V, C = verify(rom, strict_source=True)
    muts = _run_mutations(rom)

    ok = (not V) and all(m['caught'] and m['rejected'] for m in muts)
    results = {
        'tool': 'check_native_contracts.py',
        'rom': path,
        'rom_sha256': hashlib.sha256(rom).hexdigest(),
        'baseline_ok': not V,
        'baseline_violations': V,
        'unconfirmed_contracts': C['unconfirmed'],
        'negative_tests': muts,
        'negative_all_rejected': all(m['caught'] and m['rejected'] for m in muts),
        'ok': ok,
    }
    json.dump(C, open(HERE / 'contracts.json', 'w', encoding='utf-8'),
              indent=1, ensure_ascii=False)
    json.dump(results, open(HERE / 'results.json', 'w', encoding='utf-8'),
              indent=1, ensure_ascii=False)
    print('baseline violations: %d' % len(V))
    for v in V:
        print('  [%s] %s' % (v['tag'], v['message']))
    for m in muts:
        print('%-18s caught=%s rejected=%s tags=%s' %
              (m['id'], m['caught'], m['rejected'], ','.join(m['violation_tags'])))
    print('OK' if ok else 'FAILED')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
