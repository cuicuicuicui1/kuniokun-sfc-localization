SMALL_KATA = '\u30a1\u30a3\u30a5\u30a7\u30a9\u30e3\u30e5\u30e7\u30c3'
KANA_SET = set(HIRA + KATA + SMALL_HIRA + SMALL_KATA + '\u30fc\u30f3')


def glyph_table(rom):
    t = {}
    for i, ch in enumerate(SMALL_HIRA):
        t[0x66 + i] = ch          # 0x66 を, 0x67.. small hiragana
    for i, ch in enumerate(HIRA):
        t[0x71 + i] = ch
    t[0xA0] = '\u30fc'
    for i, ch in enumerate(KATA):
        t[0xA1 + i] = ch
    t[0xD5] = '\u30fc'
    t[0xD6] = '\u30f3'
    for i, ch in enumerate(SMALL_KATA):
        t[0xD7 + i] = ch
    return t


def decode_name(rom, raw):
    """Decode a 4-byte record name field; returns (string, ok)."""
    fa = rom[0x1FA9E:0x1FA9E + 256]
    tiles = glyph_table(rom)
    out = []
    for b in raw:
        if b == 0:
            break
        g = tiles.get(fa[b])
        if g is None or g not in KANA_SET:
            return ''.join(out), False
        out.append(g)
    return ''.join(out), True


