def u16(buf, off):
    return buf[off] | (buf[off + 1] << 8)


def c2f(bank, cpu):
    return bank * 0x8000 + (cpu - 0x8000)


def f2c(off):
    return off // 0x8000, 0x8000 + off % 0x8000


# 65816 instruction sizes; mode letters were generated from a complete
# opcode-mode table (same shape as source/dis65.py, embedded here so this
# checker has no imports from the build tree).
MODE_STR = EXPECT['mode_str']
SIZE_OF_MODE = {'i': 1, 'a': 1, 'm': 2, 'd': 2, 'x': 2, 'y': 2, 'X': 2,
                'Y': 2, 'Z': 2, 'L': 2, 'K': 2, 'S': 2, 'T': 2, 'A': 3,
                'B': 3, 'C': 3, 'D': 4, 'E': 4, 'R': 2, 'Q': 3, 'N': 3,
                'O': 3, 'P': 4, 'U': 3}
IMM_A = {0x09, 0x29, 0x49, 0x69, 0x89, 0xA9, 0xC9, 0xE9}
IMM_XY = {0xA0, 0xA2, 0xC0, 0xE0}


def op_size(rom, off, m8, x8):
    op = rom[off]
    md = MODE_STR[op]
    if md == 'm':
        if op in IMM_A:
            return 2 if m8 else 3
        if op in IMM_XY:
            return 2 if x8 else 3
    return SIZE_OF_MODE[md]


def sweep(rom, bank, cpu, n=0x40):
    """Linear sweep from a code anchor; tracks SEP/REP immediate widths."""
    out = []
    pc = cpu
    end = cpu + n
    m8 = x8 = True
    while pc < end:
        if not (0x8000 <= pc < 0x10000):
            break
        off = c2f(bank, pc)
        if off + 4 > len(rom):
            break
        op = rom[off]
        sz = op_size(rom, off, m8, x8)
        out.append((pc, op, sz))
        if op == 0xE2 and sz == 2:
            if rom[off + 1] & 0x20:
                m8 = True
            if rom[off + 1] & 0x10:
                x8 = True
        elif op == 0xC2 and sz == 2:
            if rom[off + 1] & 0x20:
                m8 = False
            if rom[off + 1] & 0x10:
                x8 = False
        pc += sz
    return out


def sweep_refs(rom, bank, cpu, n=0x40):
    """Long refs/returns inside the first n bytes from an entry point."""
    refs = []
    for pc, op, sz in sweep(rom, bank, cpu, n):
        off = c2f(bank, pc)
        if op in (0x22, 0x5C):
            refs.append('%s %02X:%04X' % ('JSL' if op == 0x22 else 'JML',
                                          rom[off + 3],
                                          rom[off + 1] | rom[off + 2] << 8))
        elif op == 0x4C:
            refs.append('JMP %04X' % (rom[off + 1] | rom[off + 2] << 8))
        elif op == 0x60:
            refs.append('RTS')
        elif op == 0x6B:
            refs.append('RTL')
    return refs


def align_back(rom, bank, cpu, tries=48):
    """Evidence that cpu is an instruction boundary: a linear sweep from
    cpu-k lands exactly on cpu for some k <= tries."""
    for back in range(2, tries + 1):
        start = cpu - back
        if start < 0x8000:
            continue
        pc = start
        for _ in range(40):
            if pc == cpu:
                return back
            if pc > cpu:
                break
            off = c2f(bank, pc)
            if off + 4 > len(rom):
                break
            pc += op_size(rom, off, True, True)
    return None


