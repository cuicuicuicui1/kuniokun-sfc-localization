def _run_mutations(rom):
    tests = []

    def add(tid, desc, mutate, expect_tag, strict=False):
        tests.append({'id': tid, 'description': desc,
                      'expected_violation': expect_tag,
                      'mutation': mutate, 'strict_source': strict})

    def m_src(b):
        b[0x200] ^= 0xFF
    add('N1-source-hash', 'flip a byte in bank $00 -> source sha256 must reject',
        m_src, 'source.sha256', strict=True)

    def m_name_end(b):
        b[0x48002] = 0x5A     # end $A04A -> $A05A (one extra record)
    add('N2-name-end', 'name table end $A04A -> $A05A', m_name_end, 'names.count')

    def m_name_start(b):
        b[0x48000] = 0x2E     # base $802A -> $802E
    add('N3-name-base', 'name table base $802A -> $802E', m_name_start, 'names.count')

    def m_name_anchor(b):
        b[0x4802A + 512 * 16] ^= 0x01   # first kana of record 512 (くにお)
    add('N4-name-anchor', 'corrupt record 512 first code', m_name_anchor, 'names.anchors|names.decode')

    def m_param_ptr(b):
        b[0x48005] -= 1        # first parameter pointer $A224 -> $A223... low byte
    add('N5-param-ptr', 'change the first parameter pointer', m_param_ptr, 'names.params')

    def m_ext_entry(b):
        b[0x110072] = 0x02     # ext entry[1] $8000 -> $8002
    add('N6-ext-table', 'extension table entry[1] $8000 -> $8002', m_ext_entry, 'ext.table')

    def m_ext_sentinel(b):
        b[0x110071] = 0x80     # entry[0] $0000 -> $8000
    add('N7-ext-sentinel', 'extension table sentinel != 0', m_ext_sentinel, 'ext.sentinel')

    def m_menu_rows(b):
        b[0x1F845] = 0x01      # first menu row 0 -> 1
    add('N8-menu-table', 'menu row table $03:F845[0] 00 -> 01', m_menu_rows, 'menu.tables')

    def m_blob(b):
        b[0x1F744] ^= 0x20     # a label code inside the blob
    add('N9-menu-blob', 'flip a label code in the $03:F743 blob', m_blob,
        'menu.blob')

    def m_entry_site(b):
        b[0x00E4A2] = 0xEA     # JML $20:8220 -> NOP
    add('N10-entry-site', 'NOP the JML at $01:E4A2', m_entry_site, 'entry.sites')

    def m_loader(b):
        b[0x01EBBB + 1] ^= 0x01  # loader fetch JML operand
    add('N11-loader-patch', 'change the $03:EBBB loader patch', m_loader, 'lock')

    def m_text_tail(b):
        b[0x118740] = 0x11     # revive text after the bank23 end
    add('N12-bank23-tail', 'write nonzero byte after bank23 text end', m_text_tail,
        'bank23.tail')

    out = []
    for t in tests:
        b = bytearray(rom)
        t['mutation'](b)
        V, _ = verify(bytes(b), strict_source=t['strict_source'])
        tags = sorted(set(v['tag'] for v in V))
        want = set(t['expected_violation'].split('|'))
        caught = bool(want & set(tags))
        out.append({'id': t['id'], 'description': t['description'],
                    'expected_violation': t['expected_violation'],
                    'caught': caught, 'violation_tags': tags,
                    'rejected': len(V) > 0})
    return out


